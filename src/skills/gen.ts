/**
 * @renxqoo/agent-cli-sdk/skills —— 命令文档自动生成(gen)
 *
 * 设计依据:docs/06-skills.md "自动文档生成"、"命令签名生成规则"。
 * 核心机制:AUTO-GEN 标记块(preserved regions)。
 *   - 标记块内:从 defineCommands 的 spec 自动生成(签名表 + 参数表),每次 gen 覆盖,人不要手改
 *   - 标记块外:人写的语义内容(何时用/错误处理),gen 永不触碰
 *
 * 两种策略(都用,决策清单 #15):
 *   - 策略 A(增量):只生成 ## 命令 + ### 参数说明 两节,塞进标记块 → gen <name>
 *   - 策略 B(骨架):首次吐整份 SKILL.md(带 {{FILL}} 占位),后续只刷标记块 → gen <name> --init
 */

import { compileCommandSchema, type ArgumentDescriptor } from "../command-schema.js";
import type { CommandArgs, CommandSpec, DefineCliOptions } from "../types.js";
import { stringify as stringifyYaml } from "yaml";
import { InternalError } from "../errs/index.js";
import { validateSkillName } from "./path-guard.js";

